/** undefined = the event socket (/ws); otherwise a terminal socket (/ws/pty) and the PtyManager key of the shell it shows (a Task id, or a Workspace id for a Workspace's shell). */
/** A terminal socket carries its task; either kind carries the login cookie it was let in by, to be checked again. */
export type WsData = { ptyKey: string; cwd: string; ofTask: boolean; teleport?: boolean; shell?: string; client?: PtyClient; session?: string } | { ptyKey?: undefined; session?: string } | undefined;
export type Routes = NonNullable<Parameters<typeof Bun.serve>[0]["routes"]>;
export type SuggestCtxInput = { workspaceId?: string; cwd?: string; title?: string; prompt: string; scope?: string[]; kind?: string };
// On the cloud host (the passkey login is on) a token counts only from this machine: the runners' /mcp calls and
// sb-rescue's probe. From anywhere else — CloudFront's VPC origin included — only the cookie. Judged by the connection's
// peer, never a header. A Mac (no public key) is unchanged.
export type Peer = { requestIP(r: Request): { address: string } | null } | undefined;
/** sb-rescue's view of the releases; `managed: false` when not under sb-rescue or when it does not answer. */
export type RescueStatus = ReleaseState & { previous: string | null; running?: string | null; state: string; busy: string | null; lastError: string | null };
// Every /api route except health goes through the token check when off-loopback.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export type AnyHandler = (req: any, srv: any) => any;

